#!/bin/sh
# The round screen's full arm model stays on Toby's PC: it may never be committed or pushed here. Sourced by pre-commit
# and pre-push. check_blob <path> <blob or rev:path> prints why a file is refused (nothing = allowed).
# Refused: a file named model_data*.h or arm_lod*.h, a 3D model file, or one whose text carries a model generator's
# first line (the patterns are split so this file does not match itself).
SIG1='GENERATED by tools/bake_''puck'
SIG2='Generated by P4SimTest/model/build''-model'
# the one file allowed under the old name: the stand-in as published in the commits of 2026-10-31 .. 2026-11-07
ALLOWED_BLOBS='d451cf621120d735b0a4af57974cfecfa6a33dda'

check_blob() {
  path=$1
  obj=$2
  base=${path##*/}
  case " $ALLOWED_BLOBS " in *" $(git rev-parse -q --verify "$obj" 2>/dev/null) "*) return ;; esac
  case "$base" in
    model_data*.h|arm_lod*.h)
      echo "  $path - the full arm model (or a copy of it) stays off this repository"; return ;;
  esac
  ext=$(printf '%s' "${base##*.}" | tr 'A-Z' 'a-z')
  case "$ext" in
    stl|3mf|obj|glb|gltf|step|stp|f3d|fbx|ply|igs|iges|blend)
      echo "  $path - a 3D model file"; return ;;
  esac
  if git cat-file -p "$obj" 2>/dev/null | grep -q -F -e "$SIG1" -e "$SIG2"; then
    echo "  $path - its text is generated from the full arm model"
  fi
}

refuse() {
  echo "REFUSED: the full arm model may not go into this repository:" >&2
  printf '%s\n' "$1" >&2
  echo "(firmware/Puck/model_data.h stays on this PC; the repository has model_standin.h - see .gitignore)" >&2
  exit 1
}
